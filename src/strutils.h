# pragma once
/**
 * Утилиты для работы со строками в UTF-8 (кириллица).
 *
 * Arduino String не умеет регистронезависимый поиск многобайтовых
 * последовательностей, поэтому реализованы минимальные аналоги:
 *  - toLowerUtf8() — приведение кириллицы/латиницы к нижнему регистру;
 *  - splitMessage() — разбиение текста по границам слов с учётом
 *    многобайтовых символов (аналог splitMessage из messenger.js).
 */

#include <Arduino.h>
#include <string.h>
#include <vector>

struct Utf8Pair {
    const char *lower;
    const char *upper;
};

static const Utf8Pair CYR_PAIRS[] = {
    {"а", "А"}, {"б", "Б"}, {"в", "В"}, {"г", "Г"}, {"д", "Д"}, {"е", "Е"},
    {"ж", "Ж"}, {"з", "З"}, {"и", "И"}, {"й", "Й"}, {"к", "К"}, {"л", "Л"},
    {"м", "М"}, {"н", "Н"}, {"о", "О"}, {"п", "П"}, {"р", "Р"}, {"с", "С"},
    {"т", "Т"}, {"у", "У"}, {"ф", "Ф"}, {"х", "Х"}, {"ц", "Ц"}, {"ч", "Ч"},
    {"ш", "Ш"}, {"щ", "Щ"}, {"ъ", "Ъ"}, {"ы", "Ы"}, {"ь", "Ь"}, {"э", "Э"},
    {"ю", "Ю"}, {"я", "Я"}, {"ё", "Ё"},
};
static const size_t CYR_PAIRS_COUNT = sizeof(CYR_PAIRS) / sizeof(CYR_PAIRS[0]);

/** Приведение кириллицы и латиницы к нижнему регистру (UTF-8). */
String toLowerUtf8(const String &in);

/** Обрезка пробелов с обеих сторон. */
inline String trimStr(const String &s) {
    String r = s;
    r.trim();
    return r;
}

/**
 * Разбиение текста на части не длиннее maxLen БАЙТ UTF-8 по границам слов.
 * Повторяет логику splitMessage() из messenger.js:
 *   - слова разделяются последовательностями пробельных символов;
 *   - слово длиннее лимита режется по лимиту (без разрыва UTF-8 символа);
 *   - пустые части не добавляются.
 */
std::vector<String> splitMessage(const String &text, size_t maxLen);
